/// True when `code` is a known ISO alpha-2 code (uppercase).
pub fn is_valid_country_code(code: &str) -> bool {
    COUNTRY_DIAL_CODES.iter().any(|(iso, _)| *iso == code)
}

/// Country of an E.164 phone number by longest matching dial prefix.
/// On an equal-length tie the first table entry wins, like the original.
pub fn country_iso_from_phone(phone: &str) -> Option<&'static str> {
    let digits: String = phone.chars().filter(|c| c.is_ascii_digit()).collect();
    let mut best: Option<&'static str> = None;
    let mut best_len = 0usize;
    for (iso, dial) in COUNTRY_DIAL_CODES {
        if digits.starts_with(dial) && dial.len() > best_len {
            best = Some(iso);
            best_len = dial.len();
        }
    }
    best
}
